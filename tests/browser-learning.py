from playwright.sync_api import sync_playwright, expect
import re,json,os
BASE_URL=os.environ.get("ISAI_TEST_URL","http://127.0.0.1:5173")
errors=[]; observations=[]
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 context=browser.new_context(viewport={'width':1440,'height':1000})
 page=context.new_page()
 page.on('pageerror',lambda error: errors.append(str(error)))
 page.on('console',lambda msg: errors.append('console: '+msg.text) if msg.type=='error' else None)
 page.goto(BASE_URL);page.evaluate('localStorage.clear()');page.reload();page.wait_for_timeout(500)
 page.screenshot(path='/tmp/isai-desktop.png',full_page=True)
 page.get_by_role('button',name='Notation and tonic settings').click()
 page.locator('#tonic').select_option('2');page.locator('#notation').select_option('carnatic')
 page.get_by_role('button',name='Ready to play').click()
 page.get_by_role('button',name='Play your first notes').click()
 expect(page.locator('.practice-tonic')).to_contain_text('Sa = D')
 page.get_by_role('button',name='Start practice',exact=True).click()
 page.get_by_role('button',name=re.compile('^Play C4,')).click()
 for name in ['D4','E4','F♯4','G4','A4','G4','F♯4','E4','D4']:
  page.get_by_role('button',name=re.compile('^Play '+re.escape(name)+',')).click()
 expect(page.locator('.practice-complete')).to_be_visible()
 expect(page.locator('.practice-complete')).to_contain_text('90%')
 observations.append('Transposition Sa=D, Carnatic setting, wrong-note penalty, all 9 first-notes targets and 90% completion passed.')
 page.get_by_role('button',name='My progress',exact=True).click()
 expect(page.locator('.stats-grid .stat-card').first).to_contain_text('1')
 page.reload()
 page.get_by_role('button',name='My progress',exact=True).click()
 expect(page.locator('.stats-grid .stat-card').first).to_contain_text('1')
 expect(page.locator('.level-journey')).to_contain_text('90% best')
 observations.append('Lesson score and completion persisted after browser reload.')
 page.get_by_role('button',name='Song library',exact=True).click()
 page.get_by_role('textbox',name='Search songs, films or composers').fill('Vaseegara')
 expect(page.locator('.song-grid .song-card')).to_have_count(1)
 page.get_by_role('button',name='Explore Vaseegara',exact=True).click()
 expect(page.get_by_role('dialog')).to_be_visible()
 expect(page.get_by_role('dialog')).to_contain_text('Minnale')
 expect(page.get_by_role('dialog')).to_contain_text('verified piano arrangement and recording are not included')
 page.get_by_role('button',name='Close song details').click()
 page.get_by_role('button',name='Save Vaseegara',exact=True).click()
 page.get_by_role('button',name=re.compile('^Saved songs')).click()
 expect(page.locator('.song-grid .song-card')).to_have_count(1)
 observations.append('Vaseegara search, reference detail, save and Saved songs filter passed.')
 page.get_by_role('button',name=re.compile('^All songs')).click()
 page.get_by_role('textbox',name='Search songs, films or composers').fill('')
 page.locator('.library-select select').nth(0).select_option('A. R. Rahman')
 page.locator('.library-select select').nth(1).select_option('2010')
 cards=page.locator('.song-grid .song-card')
 assert cards.count()>0
 for card in cards.all():
  assert 'A. R. Rahman' in card.inner_text(),card.inner_text()
  assert re.search('201[0-9]',card.inner_text()),card.inner_text()
 observations.append(f'Composer + 2010s filtering passed ({cards.count()} displayed).')
 page.reload();page.get_by_role('button',name='Song library',exact=True).click();page.get_by_role('button',name=re.compile('^Saved songs')).click()
 expect(page.locator('.song-title-button')).to_have_text('Vaseegara')
 observations.append('Saved song persisted after reload.')
 mobile=browser.new_context(viewport={'width':430,'height':932},is_mobile=True,has_touch=True,device_scale_factor=1)
 mp=mobile.new_page();mp.on('pageerror',lambda error:errors.append('mobile: '+str(error)))
 mp.goto(BASE_URL);mp.wait_for_timeout(400)
 mp.screenshot(path='/tmp/isai-mobile.png',full_page=True)
 measures=mp.evaluate('({width:innerWidth,scroll:document.documentElement.scrollWidth})')
 assert measures['scroll']<=measures['width'],measures
 mp.get_by_role('button',name='Play your first notes').click()
 mp.screenshot(path='/tmp/isai-mobile-practice.png',full_page=True)
 measures=mp.evaluate('({width:innerWidth,scroll:document.documentElement.scrollWidth})')
 assert measures['scroll']<=measures['width'],measures
 observations.append('iPhone 430×932 learning/practice body has no horizontal overflow; screenshots captured.')
 browser.close()
print(json.dumps({'passed':observations,'browser_errors':errors},indent=2,ensure_ascii=False))
